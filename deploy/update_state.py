#!/usr/bin/env python3
"""Generate the factual status block for CLAUDE.md (proposed ADR-006).

State is generated, not remembered. This script reads facts the repo already
holds -- the git log, the working copy, the status line of each lessons file,
the migrations and services present -- and writes them between two markers in
CLAUDE.md. It never writes rationale, lessons or decisions: those stay written
by a person (KNOWLEDGE_ARCHITECTURE.md, "crystallized thinking over raw logs").

    python deploy/update_state.py              # print the block (dry run)
    python deploy/update_state.py --write      # update CLAUDE.md in place
    python deploy/update_state.py --write --run-tests

Only the text between the markers is replaced. If CLAUDE.md has no markers,
--write appends the block at the end and leaves everything above it untouched.
Standard library only; runs on Windows and Linux.
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import subprocess
import sys
from pathlib import Path

BEGIN = "<!-- STATE:BEGIN (generated by deploy/update_state.py; do not edit by hand) -->"
END = "<!-- STATE:END -->"
_BEGIN_RE = re.compile(r"<!-- STATE:BEGIN.*?-->")
_STATUS_RE = re.compile(r"^\*\*Status:\*\*\s*(.+)$", re.MULTILINE)
_TITLE_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
MAX_LISTED = 15


def git(repo: Path, *args: str) -> str:
    """Run a read-only git command; return stdout, or '' if git is unavailable."""
    try:
        result = subprocess.run(
            ["git", "--no-optional-locks", "-C", str(repo), *args],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return result.stdout.rstrip("\n") if result.returncode == 0 else ""


def parse_lesson(text: str) -> tuple[str, str]:
    """Return (title, status) from a lessons file. Status may span wrapped lines."""
    title = _TITLE_RE.search(text)
    status = _STATUS_RE.search(text)
    status_text = "no status line"
    if status:
        lines = [status.group(1).strip()]
        for line in text[status.end():].splitlines()[1:]:
            if not line.strip() or line.startswith(("**", "#", ">", "-")):
                break
            lines.append(line.strip())
        status_text = " ".join(lines)
    return (title.group(1).strip() if title else "untitled", status_text)


def parse_porcelain(output: str) -> tuple[list[str], list[str]]:
    """Split `git status --porcelain` output into (modified, untracked) paths."""
    modified, untracked = [], []
    for line in output.splitlines():
        if len(line) < 4:
            continue
        code, path = line[:2], line[3:].strip().strip('"')
        (untracked if code == "??" else modified).append(path)
    return modified, untracked


def replace_block(document: str, block: str) -> str:
    """Replace the marked block in document, or append it if no markers exist."""
    begin = _BEGIN_RE.search(document)
    end = document.find(END, begin.end()) if begin else -1
    if begin and end != -1:
        return document[:begin.start()] + block + document[end + len(END):]
    separator = "" if document.endswith("\n\n") else ("\n" if document.endswith("\n") else "\n\n")
    return document + separator + block + "\n"


def _listed(paths: list[str]) -> list[str]:
    lines = [f"  - `{p}`" for p in paths[:MAX_LISTED]]
    if len(paths) > MAX_LISTED:
        lines.append(f"  - ...and {len(paths) - MAX_LISTED} more")
    return lines


def run_tests(repo: Path) -> str:
    try:
        result = subprocess.run(
            [sys.executable, "-B", "-m", "unittest", "discover", "-s", "tests", "-t", "."],
            cwd=repo, capture_output=True, text=True, timeout=300,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        return f"could not run ({type(error).__name__})"
    summary = [l for l in result.stderr.splitlines() if l.startswith(("Ran ", "OK", "FAILED"))]
    return "; ".join(summary) if summary else f"exit code {result.returncode}"


def build_block(repo: Path, now: dt.datetime, with_tests: bool = False) -> str:
    out = [BEGIN, "## Generated state", ""]
    out.append(f"Generated {now.strftime('%Y-%m-%d %H:%M')} from the repo. "
               "Facts only; rationale lives in `Docs/lessons/` and the ADRs.")
    out.append("")

    # --- slices, from the lessons files -----------------------------------
    out.append("**Slices** (status line of each lessons file)")
    lessons = sorted((repo / "Docs" / "lessons").glob("*.md"))
    if lessons:
        for path in lessons:
            title, status = parse_lesson(path.read_text(encoding="utf-8", errors="replace"))
            out.append(f"- {title}: {status}")
    else:
        out.append("- no lessons files found")
    out.append("")

    # --- commits -----------------------------------------------------------
    branch = git(repo, "rev-parse", "--abbrev-ref", "HEAD") or "unknown"
    last = git(repo, "log", "-1", "--format=%cs")
    out.append(f"**Last commits** (branch `{branch}`)")
    log = git(repo, "log", "-8", "--format=- %cs %s")
    out.extend(log.splitlines() if log else ["- git log unavailable"])
    if last:
        try:
            age = (now.date() - dt.date.fromisoformat(last)).days
            out.append(f"- Days since last commit: {age}")
        except ValueError:
            pass
    out.append("")

    # --- working copy ------------------------------------------------------
    modified, untracked = parse_porcelain(git(repo, "status", "--porcelain"))
    out.append("**Working copy**")
    if not modified and not untracked:
        out.append("- clean")
    if modified:
        out.append(f"- {len(modified)} modified, uncommitted:")
        out.extend(_listed(modified))
    if untracked:
        out.append(f"- {len(untracked)} untracked:")
        out.extend(_listed(untracked))
    out.append("")

    # --- what exists -------------------------------------------------------
    migrations = sorted(p.name for p in (repo / "schemas").glob("*.sql"))
    services = sorted(p.parent.name for p in (repo / "services").glob("*/__main__.py"))
    tests = sorted(p.name for p in (repo / "tests").glob("test_*.py"))
    out.append("**Present in the repo**")
    out.append(f"- Migrations: {', '.join(migrations) if migrations else 'none'}")
    out.append(f"- Services: {', '.join(services) if services else 'none'}")
    out.append(f"- Test files: {len(tests)}")
    if with_tests:
        out.append(f"- Test run: {run_tests(repo)}")
    out.append("")
    out.append("Not covered here: what is running on Inferno or the Sensor Pi. "
               "Check those with the health endpoints.")
    out.append(END)
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--write", action="store_true", help="update CLAUDE.md in place")
    parser.add_argument("--run-tests", action="store_true", help="run the unit tests and record the result")
    args = parser.parse_args(argv)

    block = build_block(args.repo, dt.datetime.now(), args.run_tests)
    if not args.write:
        print(block)
        return 0

    target = args.repo / "CLAUDE.md"
    original = target.read_text(encoding="utf-8") if target.exists() else ""
    updated = replace_block(original, block)
    if updated != original:
        target.write_text(updated, encoding="utf-8", newline="\n")
        print(f"updated {target}")
    else:
        print("no change")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
